let x = 10;
let y = 4;

// if
if (x != 10)
    console.log(`nilai x adalah ${x}`);


// if else
if (x != 10)
    console.log(`nilai x adalah ${x}`);
else
    console.log(`nilai tidak ditemukan`);


// else if
if (x != 10)
    console.log(`nilai x adalah ${x}`);
else if (y != 4)
    console.log(`nilai y adalah ${y}`);
else
    console.log(`nilai tidak ditemukan`);


// switch case
switch (x) {
    case 10:
        console.log(`nilai x adalah ${x}`);
        break;
    case 20:
        console.log(`nilai x adalah ${x}`);
        break;
    default:
        console.log(`nilai tidak ditemukan`);
        break;
}